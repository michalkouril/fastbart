#!/usr/bin/env python3
"""Turn a copy of the BART g-formula bootstrap package into the GPU pipeline.

Usage: make_pipeline.py <bootstrap package folder> <fast estimator, e.g. BART_gformula_week6_mean_fastbart.R>

Writes into the package folder:
  estimator_gpu_prep.R    the estimator up to its titer fits; exports the six titer training sets (gpu_export) and saves
                          the R session
  estimator_gpu_finish.R  reads the six GPU fits (gpu_import) and runs the rest of the estimator unchanged
  run_bootstrap_gpu.R     the bootstrap driver in three phases (prep on the CPU, all titer fits on the GPU, finish on the
                          CPU); setup, combine() and the summary printout are taken from run_bootstrap_bart_week6.R
and copies gpu_bart.R and bootstrap_worker_gpu.R from this folder. The package's own files are not changed.
"""
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def read(path):
    with open(path, newline="") as f:
        return f.read().replace("\r\n", "\n")


def split_estimator(est):
    a = est.index("titer_fit <- list()\n")
    b = est.index("titer_sl <- lapply(titer_fit, slice_fit)")
    head, loop, tail = est[:a], est[a:b], est[b:]
    i = loop.index("  titer_fit[[w]] <- ")
    j = loop.index("ndpost = ndpost, nskip = nskip, printevery = 10000)", i) + len("ndpost = ndpost, nskip = nskip, printevery = 10000)")
    loop = loop[:i] + ('  gpu_info[[w]] <- gpu_export(d[ix, pc, drop = FALSE], d[ix, tgt], wt, file.path(GPU_DIR, sprintf("titer%d", w)), '
                       "ndpost, nskip)") + loop[j:]
    loop = loop.replace("titer_fit <- list()\n", "gpu_info <- list()\n", 1).replace("model: fit on", "model: exported", 1)
    prep = ("# Phase 1 of the GPU pipeline: everything before the titer fits; exports the six titer training sets and saves the session.\n"
            'GPU_DIR <- Sys.getenv("SIM_OUT_DIR")\n' + head + loop + 'save.image(file.path(GPU_DIR, "state.RData"))\n')
    finish = ("# Phase 3 of the GPU pipeline (after bart_gpu): reads the six titer fits and runs the rest of the estimator unchanged.\n"
              'titer_fit <- lapply(1:6, function(w) gpu_import(file.path(GPU_DIR, sprintf("titer%d", w)), gpu_info[[w]]))\n' + tail)
    return prep, finish


def make_driver(drv):
    setup = drv[drv.index("args <- commandArgs(trailingOnly = TRUE)"):drv.index("RS <- ")]
    setup = setup.replace('if (Sys.getenv("NDPOST") == "") Sys.setenv(NDPOST = "50")', 'if (Sys.getenv("NDPOST") == "") Sys.setenv(NDPOST = "100")')
    mid = drv[drv.index("RS <- "):drv.index("rep_file <- function(b)")]
    mid = "\n".join(l for l in mid.split("\n") if not l.startswith("RS <- ") and not l.startswith("WORKER <- "))
    helpers = drv[drv.index("rep_file <- function(b)"):drv.index("combine <- function() {")]
    combine = drv[drv.index("combine <- function() {"):drv.index("todo <- ")]
    printout = drv[drv.index("if (!is.null(sm)) {"):]
    return ('''# GPU pipeline version of run_bootstrap_bart_week6.R (generated by fastbart's gpu/make_pipeline.py): same resamples,
# estimator and summaries, but the six titer BART fits of every replicate are fitted together on the GPU (bart_gpu).
# Phases: 1) prep (CPU, n_par workers): data, CBPS, hazard model (fastbart::fpbart), titer training sets; 2) GPU: all
# titer fits in one batch; 3) finish (CPU, n_par workers): simulation and summaries (fastbart::compile_trees / predict_draw).
# Usage: Rscript run_bootstrap_gpu.R [B = 100] [n_parallel = 10] [seed = 1]; env BART_GPU (path of bart_gpu),
# BART_GPU_THREADS (threads per fit, default 256).
''' + setup + '''RS <- "Rscript"
WORKER <- file.path(BASE, "bootstrap_worker_gpu.R")
GPU_BIN <- Sys.getenv("BART_GPU", "bart_gpu")
GPU_THREADS <- Sys.getenv("BART_GPU_THREADS", "256")
''' + mid + helpers + combine + '''
todo <- 0:B
cat(sprintf("Seed %d, B = %d (replicate 0 = original data), GPU pipeline, %d CPU workers, NDPOST = %s, tag '%s'\\n", seed, B, n_par, Sys.getenv("NDPOST"), TAG))
run_phase <- function(phase, reps) parallel::mclapply(reps, function(b) system2(RS, c(shQuote(WORKER), b, phase), stdout = FALSE, stderr = FALSE),
                                                    mc.cores = n_par, mc.preschedule = FALSE)
t0 <- Sys.time()
invisible(run_phase("prep", todo))
t1 <- Sys.time()
ok <- todo[file.exists(file.path(Sys.getenv("BOOT_SCRATCH"), sprintf("rep_%03d", todo), "state.RData"))]
fitlist <- file.path(Sys.getenv("BOOT_SCRATCH"), "fits.txt")
writeLines(unlist(lapply(ok, function(b) sprintf("%s %d", file.path(Sys.getenv("BOOT_SCRATCH"), sprintf("rep_%03d", b), sprintf("titer%d", 1:6)),
                                                   12345L + 7L * b + 1:6))), fitlist)
gpu_out <- system2(GPU_BIN, c(shQuote(fitlist), GPU_THREADS), stdout = TRUE, stderr = TRUE)
cat(gpu_out, sep = "\\n")
t2 <- Sys.time()
invisible(run_phase("finish", ok))
t3 <- Sys.time()
sm <- combine()
mins <- function(a, b) as.numeric(difftime(b, a, units = "mins"))
cat(sprintf("Phases: prep %.1f min, GPU %.1f min, finish %.1f min\\n", mins(t0, t1), mins(t1, t2), mins(t2, t3)))
cat(sprintf("\\nDone. Total time: %.1f min.\\n", mins(t0, t3)))
''' + printout)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    pkg, fast = sys.argv[1], sys.argv[2]
    prep, finish = split_estimator(read(fast))
    driver = make_driver(read(os.path.join(pkg, "run_bootstrap_bart_week6.R")))
    for name, text in [("estimator_gpu_prep.R", prep), ("estimator_gpu_finish.R", finish), ("run_bootstrap_gpu.R", driver)]:
        with open(os.path.join(pkg, name), "w") as f:
            f.write(text)
    for name in ["gpu_bart.R", "bootstrap_worker_gpu.R"]:
        shutil.copy(os.path.join(HERE, name), os.path.join(pkg, name))
    print("GPU pipeline written to", pkg)


if __name__ == "__main__":
    main()
